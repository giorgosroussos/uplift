<?php

/**
 * Generates deptrac.yaml from the components and their may_depend_on rules in
 * design/model/architecture.yaml (ARCH-004). Never edit deptrac.yaml by hand;
 * a test fails when it is out of date.
 *
 * Usage: php scripts/generate-deptrac.php [--check]
 */

use Symfony\Component\Yaml\Yaml;

require __DIR__.'/../vendor/autoload.php';

/**
 * @return array<string, list<string>> module name => module names it may depend on
 */
function uplift_module_rules(string $architectureFile): array
{
    /** @var array{components: list<array{id: string, may_depend_on?: list<string>}>} $architecture */
    $architecture = Yaml::parseFile($architectureFile);

    $toModule = static fn (string $componentId): string => substr($componentId, strlen('CMP-'));

    $rules = [];
    foreach ($architecture['components'] as $component) {
        $rules[$toModule($component['id'])] = array_map($toModule, $component['may_depend_on'] ?? []);
    }

    return $rules;
}

/**
 * @param  array<string, list<string>>  $rules
 * @param  list<string>  $paths
 */
function uplift_deptrac_yaml(array $rules, array $paths = ['./app/Modules']): string
{
    $layers = [];
    foreach (array_keys($rules) as $module) {
        $layers[] = [
            'name' => $module,
            'collectors' => [
                ['type' => 'classLike', 'value' => '^App\\\\Modules\\\\'.$module.'\\\\.*'],
            ],
        ];
    }

    $config = [
        'deptrac' => [
            'paths' => $paths,
            'layers' => $layers,
            'ruleset' => array_map(static fn (array $deps): array => $deps, $rules),
        ],
    ];

    $header = "# GENERATED by scripts/generate-deptrac.php from design/model/architecture.yaml\n"
        ."# (components[].may_depend_on). Do not edit by hand.\n";

    return $header.Yaml::dump($config, 6, 4, Yaml::DUMP_EMPTY_ARRAY_AS_SEQUENCE);
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    $root = dirname(__DIR__);
    $yaml = uplift_deptrac_yaml(uplift_module_rules($root.'/design/model/architecture.yaml'));
    $target = $root.'/deptrac.yaml';

    if (in_array('--check', $argv, true)) {
        if (! is_file($target) || file_get_contents($target) !== $yaml) {
            fwrite(STDERR, "deptrac.yaml is out of date; run php scripts/generate-deptrac.php\n");
            exit(1);
        }
        exit(0);
    }

    file_put_contents($target, $yaml);
    echo "wrote deptrac.yaml\n";
}
